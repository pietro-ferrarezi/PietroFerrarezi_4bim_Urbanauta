DROP TABLE IF EXISTS Participacao, Manifestacao_Interesse, Assinatura, Peticao, Responsavel_Iniciativa, Iniciativa, Projeto, Categoria, Estado_Atividade, Estado_Manifestacao, Estado_Participacao, Voluntario, Colaborador, Usuario; 

CREATE TABLE public.Usuario (
    ID_USUARIO SERIAL PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email TEXT NOT NULL,
    senha TEXT NOT NULL
);

CREATE TABLE public.Voluntario (
    ID_VOLUNTARIO SERIAL PRIMARY KEY,
    ID_USUARIO INT UNIQUE NOT NULL,
    FOREIGN KEY (ID_USUARIO) REFERENCES public.Usuario(ID_USUARIO)
);

CREATE TABLE public.Colaborador (
    ID_COLABORADOR SERIAL PRIMARY KEY,
    ID_USUARIO INT UNIQUE NOT NULL,
    FOREIGN KEY (ID_USUARIO) REFERENCES public.Usuario(ID_USUARIO)
);

CREATE TABLE public.Categoria (
    ID_CATEGORIA SERIAL PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

CREATE TABLE public.Estado_Atividade (
    ID_ESTADO_ATIV SERIAL PRIMARY KEY,
    nome VARCHAR(50) NOT NULL
);
CREATE TABLE public.Estado_Manifestacao (
    ID_ESTADO_MANIS SERIAL PRIMARY KEY,
    nome VARCHAR(50) NOT NULL
);
CREATE TABLE public.Estado_Participacao (
    ID_ESTADO_PART SERIAL PRIMARY KEY,
    nome VARCHAR(50) NOT NULL
);

CREATE TABLE public.Projeto (
    ID_PROJETO SERIAL PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    descricao VARCHAR(500),
    ID_CATEGORIA INT NOT NULL,
    ID_ESTADO INT NOT NULL,
    ID_COLABORADOR_CRIADOR INT NOT NULL,
    FOREIGN KEY (ID_CATEGORIA) REFERENCES public.Categoria(ID_CATEGORIA),
    FOREIGN KEY (ID_ESTADO) REFERENCES public.Estado_Atividade(ID_ESTADO_ATIV),
    FOREIGN KEY (ID_COLABORADOR_CRIADOR) REFERENCES public.Colaborador(ID_COLABORADOR)
);

CREATE TABLE public.Iniciativa (
    ID_INICIATIVA SERIAL PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    descricao VARCHAR(500),
    localizacao TEXT NOT NULL,
    data_inicio TIMESTAMP NOT NULL,
-- VERIFICAR NECESSIDADE DE FIM:
    data_fim TIMESTAMP,
    CHECK (data_fim >= data_inicio),
    vagas INT NOT NULL CHECK (vagas > 0),
    ID_PROJETO INT NOT NULL,
    ID_ESTADO INT NOT NULL,
    FOREIGN KEY (ID_PROJETO) REFERENCES public.Projeto(ID_PROJETO),
    FOREIGN KEY (ID_ESTADO) REFERENCES public.Estado_Atividade(ID_ESTADO_ATIV)
);

CREATE TABLE public.Responsavel_Iniciativa (
    ID_INICIATIVA INT NOT NULL,
    ID_COLABORADOR INT NOT NULL,
    FOREIGN KEY (ID_INICIATIVA) REFERENCES public.Iniciativa(ID_INICIATIVA),
    FOREIGN KEY (ID_COLABORADOR) REFERENCES public.Colaborador(ID_COLABORADOR),
    PRIMARY KEY(ID_INICIATIVA, ID_COLABORADOR)
);

CREATE TABLE public.Manifestacao_Interesse (
    ID_MANIFESTACAO SERIAL PRIMARY KEY,
    data TIMESTAMP NOT NULL,
    ID_VOLUNTARIO INT NOT NULL,
    ID_INICIATIVA INT NOT NULL,
    UNIQUE(ID_VOLUNTARIO, ID_INICIATIVA),
    ID_ESTADO INT NOT NULL,
    FOREIGN KEY (ID_VOLUNTARIO) REFERENCES public.Voluntario(ID_VOLUNTARIO),
    FOREIGN KEY (ID_INICIATIVA) REFERENCES public.Iniciativa(ID_INICIATIVA),
    FOREIGN KEY (ID_ESTADO) REFERENCES public.Estado_Manifestacao(ID_ESTADO_MANIS)
);

CREATE TABLE public.Participacao (
    ID_PARTICIPACAO SERIAL PRIMARY KEY,
    data_confirmacao TIMESTAMP NOT NULL,
    ID_MANIFESTACAO INT UNIQUE NOT NULL,
    ID_ESTADO INT NOT NULL,
    FOREIGN KEY (ID_MANIFESTACAO) REFERENCES public.Manifestacao_Interesse(ID_MANIFESTACAO),
    FOREIGN KEY (ID_ESTADO) REFERENCES public.Estado_Participacao(ID_ESTADO_PART)
);

CREATE TABLE public.Peticao (
    ID_PETICAO SERIAL PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    descricao VARCHAR(500),
    meta_assinatura INT NOT NULL CHECK (meta_assinatura > 0),
    data_criacao TIMESTAMP NOT NULL,
    ID_COLABORADOR_CRIADOR INT NOT NULL,
    FOREIGN KEY (ID_COLABORADOR_CRIADOR) REFERENCES public.Colaborador(ID_COLABORADOR)
);

CREATE TABLE public.Assinatura (
    ID_VOLUNTARIO INT NOT NULL,
    ID_PETICAO INT NOT NULL,
    data TIMESTAMP NOT NULL,
    FOREIGN KEY (ID_VOLUNTARIO) REFERENCES public.Voluntario(ID_VOLUNTARIO),
    FOREIGN KEY (ID_PETICAO) REFERENCES public.Peticao(ID_PETICAO),
    PRIMARY KEY (ID_VOLUNTARIO, ID_PETICAO)
);

